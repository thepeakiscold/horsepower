#!/usr/bin/env python3
"""Vendor the daemon's crates so the package can be built without network.

Debian and Launchpad builders have no network access during a build, while
``cargo`` wants to reach crates.io. Running this once and committing the
result makes ``cargo build --offline`` work forever after:

    python3 scripts/vendor-rust.py

It writes ``rust/horsepowerd/vendor/`` (about 12 MB) and a
``rust/horsepowerd/.cargo/config.toml`` that points cargo at it. The vendored
tree is only needed for offline builds; ``scripts/build-deb.py`` and
``debian/rules`` prefer it automatically when it exists.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CRATE = ROOT / "rust" / "horsepowerd"
VENDOR = CRATE / "vendor"
CONFIG = CRATE / ".cargo" / "config.toml"


def main() -> int:
    cargo = shutil.which("cargo") or str(Path.home() / ".cargo" / "bin" / "cargo")
    if not Path(cargo).is_file() and shutil.which("cargo") is None:
        print("cargo not found", file=sys.stderr)
        return 1

    if VENDOR.exists():
        shutil.rmtree(VENDOR)
    print(f"Vendoring into {VENDOR} …")
    subprocess.run(
        [cargo, "vendor", "--locked", str(VENDOR)],
        cwd=CRATE,
        check=True,
    )

    CONFIG.parent.mkdir(parents=True, exist_ok=True)
    CONFIG.write_text(
        "# Generated by scripts/vendor-rust.py — makes the build offline.\n"
        "[source.crates-io]\n"
        'replace-with = "vendored-sources"\n'
        "\n"
        "[source.vendored-sources]\n"
        'directory = "vendor"\n',
        encoding="utf-8",
    )
    size = sum(path.stat().st_size for path in VENDOR.rglob("*") if path.is_file())
    print(f"Vendored {size / 1_048_576:.1f} MB; wrote {CONFIG.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
